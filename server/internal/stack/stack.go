// Package stack writes and runs the Docker Compose bundle: Immich (server, machine learning),
// Nextcloud (+ cron), one PostgreSQL holding both databases, and one Valkey (Redis).
package stack

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"text/template"
)

// Versions are pinned so an update is a deliberate change in ics-server.
const (
	ImmichVersion  = "v2"
	PostgresImage  = "ghcr.io/immich-app/postgres:14-vectorchord0.4.3-pgvectors0.2.0"
	ValkeyImage    = "docker.io/valkey/valkey:8-bookworm"
	NextcloudImage = "docker.io/library/nextcloud:31-apache"
	ProjectName    = "immcloudscale"
)

type Params struct {
	DataDir         string
	ImmichPort      int
	NextcloudPort   int
	MachineLearning bool
	DBPassword      string
	NCDBPassword    string
	NCAdminPassword string
	TrustedDomains  []string
}

