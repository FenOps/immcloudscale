// Nextcloud's database lives in the same PostgreSQL as Immich's; this runs on first start only.
const initDB = `#!/bin/bash
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname postgres <<-EOSQL
	CREATE USER nextcloud WITH PASSWORD '${NC_DB_PASSWORD}' CREATEDB;
	CREATE DATABASE nextcloud OWNER nextcloud TEMPLATE template0 ENCODING 'UTF8';
EOSQL
`

func Compose(p Params) (string, error) {
	var b bytes.Buffer
	err := composeTmpl.Execute(&b, p)
	return b.String(), err
}

func Env(p Params) string {
	return strings.Join([]string{
		"IMMICH_VERSION=" + ImmichVersion,
		"DATA_DIR=" + p.DataDir,
		fmt.Sprintf("IMMICH_PORT=%d", p.ImmichPort),
		fmt.Sprintf("NEXTCLOUD_PORT=%d", p.NextcloudPort),
		"DB_PASSWORD=" + p.DBPassword,
		"NC_DB_PASSWORD=" + p.NCDBPassword,
		"NC_ADMIN_PASSWORD=" + p.NCAdminPassword,
		"NC_TRUSTED_DOMAINS=" + strings.Join(p.TrustedDomains, " "),
	}, "\n") + "\n"
}

// Write puts docker-compose.yml, .env and initdb/ into dir and creates the data folders.
func Write(dir string, p Params) error {
	compose, err := Compose(p)
	if err != nil {
		return err
	}
	for _, d := range []string{dir, filepath.Join(p.DataDir, "photos"), filepath.Join(p.DataDir, "files"), filepath.Join(p.DataDir, "database")} {
		if err := os.MkdirAll(d, 0o750); err != nil {
			return err
		}
	}
	// The init script runs as the container's postgres user, so it must be world-readable.
	initdir := filepath.Join(dir, "initdb")
	if err := os.MkdirAll(initdir, 0o755); err != nil {
		return err
	}
	if err := os.Chmod(initdir, 0o755); err != nil {
		return err
	}
	_ = os.Chmod(dir, 0o755)
	// Nextcloud's data folder must belong to www-data (uid 33) inside the container.
	_ = os.Chown(filepath.Join(p.DataDir, "files"), 33, 33)
	_ = os.Chmod(filepath.Join(p.DataDir, "files"), 0o770)
	files := map[string]struct {
		body string
		mode os.FileMode
	}{
		"docker-compose.yml":     {compose, 0o644},
		".env":                   {Env(p), 0o600},
		"initdb/10-nextcloud.sh": {initDB, 0o755},
	}
	for name, f := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(f.body), f.mode); err != nil {
			return err
		}
	}
	return nil
}

// Runner is how the server drives Docker; faked in tests.
type Runner interface {
	Up(dir string) error
	Pull(dir string) error
	Services(dir string) ([]Service, error)
	Exec(dir, service string, args ...string) (string, error)
}

type Service struct {
	Name   string `json:"name"`
	State  string `json:"state"`
	Health string `json:"health"`
	Status string `json:"status"`
}

type Docker struct{}

func (Docker) compose(dir string, args ...string) *exec.Cmd {
	cmd := exec.Command("docker", append([]string{"compose", "--project-directory", dir}, args...)...)
	cmd.Dir = dir
	return cmd
}

func (d Docker) run(dir string, args ...string) (string, error) {
	out, err := d.compose(dir, args...).CombinedOutput()
	if err != nil {
		return string(out), fmt.Errorf("docker compose %s: %v\n%s", strings.Join(args, " "), err, out)
	}
	return string(out), nil
}

func (d Docker) Up(dir string) error {
	_, err := d.run(dir, "up", "-d", "--remove-orphans")
	return err
}

// Pull downloads the images, showing Docker's progress (setup's slowest step on a slow connection).
func (d Docker) Pull(dir string) error {
	cmd := d.compose(dir, "pull")
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("docker compose pull: %w", err)
	}
	return nil
}

func (d Docker) Exec(dir, service string, args ...string) (string, error) {
	return d.run(dir, append([]string{"exec", "-T", service}, args...)...)
}

func (d Docker) Services(dir string) ([]Service, error) {
	out, err := d.compose(dir, "ps", "--all", "--format", "json").Output()
	if err != nil {
		return nil, err
	}
	return ParsePS(out), nil
}

// ParsePS reads `docker compose ps --format json`, which is either a JSON array or one object per line.
func ParsePS(out []byte) []Service {
	type row struct {
		Service string `json:"Service"`
		State   string `json:"State"`
		Health  string `json:"Health"`
		Status  string `json:"Status"`
	}
	var rows []row
	trim := bytes.TrimSpace(out)
	if len(trim) > 0 && trim[0] == '[' {
		_ = json.Unmarshal(trim, &rows)
	} else {
		for _, line := range bytes.Split(trim, []byte("\n")) {
			var r row
			if json.Unmarshal(line, &r) == nil && r.Service != "" {
				rows = append(rows, r)
			}
		}
	}
	res := make([]Service, 0, len(rows))
	for _, r := range rows {
		res = append(res, Service{r.Service, r.State, r.Health, r.Status})
	}
	return res
}
